/**
 * Числа в тексте — одно правило для всех сторожей чисел (`numbers.test.mjs`,
 * `briefs.test.mjs`): «11,000+», «97.9%», «~3», «22». Часть слова (Qwen3,
 * I-H12) — не число.
 *
 * ⚠ Запятая — только ВНУТРИ числа. Прежний шаблон `\d[\d,]*` съедал и
 * запятую-знак препинания: в «600/600, 0 errors» он видел число «600,», и
 * сторож требовал источник для строки с запятой. На текстах сайта это молчало
 * по везению — там запятая после числа не встречалась; первый же бриф
 * наткнулся.
 */
export function numbers(text) {
  return [
    ...text.matchAll(/(?<![\w.])~?(\d(?:[\d,]*\d)?(?:\.\d+)?)\+?%?(?![\w])/g),
  ].map((m) => m[1]);
}
